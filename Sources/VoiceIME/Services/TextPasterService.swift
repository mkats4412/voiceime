import AppKit
import Carbon
import ApplicationServices

public final class TextPasterService {
    public static let shared = TextPasterService()

    // クリップボード履歴除外用の標準タイプ識別子
    private let transientType = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    private let concealedType = NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType")
    private let autoGeneratedType = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")

    private struct PasteboardBackupItem {
        let types: [NSPasteboard.PasteboardType]
        let dataMap: [NSPasteboard.PasteboardType: Data]
    }

    private init() {}

    /// 指定されたテキストをアクティブなウィンドウのカーソル位置へ自動ペースト
    /// クリップボード履歴ツールへの登録を防止（TransientType, ConcealedType）
    public func paste(text: String, restoreClipboard: Bool = true, completion: (@Sendable () -> Void)? = nil) {
        guard !text.isEmpty else {
            completion?()
            return
        }

        let pasteboard = NSPasteboard.general

        // 1. 元のクリップボード内容をバックアップ
        let backup: [PasteboardBackupItem]? = restoreClipboard ? backupPasteboard(pasteboard) : nil

        // 2. クリップボードをクリアし、履歴残存防止フラグを付与してテキストをセット
        pasteboard.clearContents()

        let item = NSPasteboardItem()
        item.setString(text, forType: .string)

        // 履歴除外・機密データマーカーを設定
        let markerData = Data()
        item.setData(markerData, forType: transientType)
        item.setData(markerData, forType: concealedType)
        item.setData(markerData, forType: autoGeneratedType)

        pasteboard.writeObjects([item])
        // 自分が書き込んだ時点の changeCount（復元時に、ユーザーがその間にコピーした内容を上書きしないため）
        let ourChangeCount = pasteboard.changeCount

        // 3. Cmd + V キーストロークをエミュレートしてテキストを挿入
        simulatePasteKeystroke()

        // 4. ペースト完了を見計らい、元のクリップボード内容を復元
        // ※長文テキストや重いアプリ（Electron/Web等）がCmd+Vを受信してPasteboardから読み取る前に
        // 復元（上書き）されてペーストが消失するレースコンディションを完全防止（最低0.35秒、文字数に応じた猶予）
        if restoreClipboard, let backup = backup {
            let restoreDelay: Double = max(0.35, min(0.60, 0.25 + Double(text.count) * 0.001))
            DispatchQueue.main.asyncAfter(deadline: .now() + restoreDelay) { [weak self] in
                // completion は self の生存に関わらず必ず呼ぶ（呼び出し側の状態が .pasting のまま固まるのを防止）
                defer { completion?() }
                guard let self = self, pasteboard.changeCount == ourChangeCount else { return }
                self.restorePasteboard(pasteboard, from: backup)
            }
        } else {
            completion?()
        }
    }

    /// 現在のクリップボード全アイテムをメモリに退避
    private func backupPasteboard(_ pasteboard: NSPasteboard) -> [PasteboardBackupItem] {
        guard let items = pasteboard.pasteboardItems else { return [] }

        return items.compactMap { item in
            var dataMap: [NSPasteboard.PasteboardType: Data] = [:]
            for type in item.types {
                if let data = item.data(forType: type) {
                    dataMap[type] = data
                }
            }
            return PasteboardBackupItem(types: item.types, dataMap: dataMap)
        }
    }

    /// 退避していたクリップボード内容を復元
    private func restorePasteboard(_ pasteboard: NSPasteboard, from backup: [PasteboardBackupItem]) {
        guard !backup.isEmpty else { return }

        pasteboard.clearContents()
        var newItems: [NSPasteboardItem] = []

        for backupItem in backup {
            let item = NSPasteboardItem()
            for (type, data) in backupItem.dataMap {
                item.setData(data, forType: type)
            }
            newItems.append(item)
        }

        pasteboard.writeObjects(newItems)
    }

    /// CGEvent を用いて Cmd+V (キーストローク) を送信
    private func simulatePasteKeystroke() {
        let isTrusted = AXIsProcessTrusted()
        if !isTrusted {
            NSLog("[VoiceIME] ⚠️ 警告: アクセシビリティ権限（補助機能）が付与されていません。「システム設定 > プライバシーとセキュリティ > アクセシビリティ」でVoiceIMEを許可してください。")
        }

        // kVK_ANSI_V = 0x09
        let keyCode: CGKeyCode = 0x09
        // combinedSessionState を使用して物理キー（Control等）のHID残存干渉を排除
        let source = CGEventSource(stateID: .combinedSessionState)

        guard let keyDown = CGEvent(keyboardEventSource: source, virtualKey: keyCode, keyDown: true),
              let keyUp = CGEvent(keyboardEventSource: source, virtualKey: keyCode, keyDown: false) else {
            NSLog("[VoiceIME] ⚠️ CGEvent の作成に失敗しました")
            return
        }

        // 確実に Command キーのみを付与し、他の物理キー（ControlやShift等）のフラグを排除
        keyDown.flags = .maskCommand
        keyUp.flags = .maskCommand

        keyDown.post(tap: .cghidEventTap)
        // アプリ側（VSCode, Chrome, Slack等）のイベントループが確実に認識できるよう十分な押下時間（25ms）を確保
        usleep(25000) // 25ms
        keyUp.post(tap: .cghidEventTap)
    }
}
